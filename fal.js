const btn = document.getElementById("falBtn");

// شروع با حالت مخفی
document.getElementById("poetName").style.display = "none";
document.getElementById("poem").style.display = "none";
document.getElementById("meaning").style.display = "none";

btn.addEventListener("click", function () {
    let randomIndex = Math.floor(Math.random() * falList.length);
    let fal = falList[randomIndex];

    document.getElementById("poetName").innerHTML = "🌸 فال امروز از " + fal.poet;
    document.getElementById("poetName").style.display = "block";

    document.getElementById("poem").innerHTML = fal.poem.replace(/\n/g, "<br>");
    document.getElementById("poem").style.display = "block";

    document.getElementById("meaning").innerHTML = "<strong>✨ برداشت امروزی:</strong><br><br>" + fal.meaning;
    document.getElementById("meaning").style.display = "block";
});